import { existsSync } from 'node:fs';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import {
  eventLeaguePriorFrom,
  summariseEventSeason,
} from '../../lib/analysis/event-projection.js';
import {
  summariseTeamSeason,
  teamMatchesFrom,
} from '../../lib/analysis/team-strength.js';
import { encodeSeasonSummary, previousSeason } from '../../lib/build-projections.js';
import type { PlayerGameweekRow } from '../../lib/dataset/player-gameweek.js';
import { EVAL_SPLITS } from '../../lib/eval/splits.js';
import { DERIVED_DIR } from './config.js';
import { writeFileAtomically } from './http.js';

const PRIOR_FILE = join(import.meta.dirname, '..', '..', 'lib', 'projection-prior.ts');
// enough to keep every rate to well under a hundredth of a point
const STORED_DECIMALS = 3;

// npm run data:prior: last season, boiled down to the totals the live
// prediction's two models read, as a typed constant the server imports. reading last
// season as history is all it does; nothing is fitted or scored on it
async function main(): Promise<void> {
  const season = previousSeason(EVAL_SPLITS.live[0]);
  const path = join(DERIVED_DIR, `player-gameweeks-${season}.json`);
  if (!existsSync(path))
    throw new Error(`${path} is missing. run npm run data:build first`);
  // data:build wrote these from rows that passed lib/dataset validation
  const rows = JSON.parse(await readFile(path, 'utf8')) as PlayerGameweekRow[];

  const byCode = new Map<number, PlayerGameweekRow[]>();
  for (const row of [...rows].sort((a, b) =>
    a.kickoffTime.localeCompare(b.kickoffTime),
  )) {
    const group = byCode.get(row.playerCode);
    if (group === undefined) byCode.set(row.playerCode, [row]);
    else group.push(row);
  }
  const round = (value: number) => Number(value.toFixed(STORED_DECIMALS));
  const players = [...byCode]
    .sort(([a], [b]) => a - b)
    .map(([code, group]) => {
      // a player who changed position is summed under the one he ended on
      const position = group.at(-1)?.position ?? 'MID';
      return `    ${code}: [${encodeSeasonSummary(summariseEventSeason(group, position)).map(round).join(', ')}],`;
    });
  const rounded = (value: unknown) =>
    JSON.parse(
      JSON.stringify(value, (_, entry: unknown) =>
        typeof entry === 'number' ? round(entry) : entry,
      ),
    ) as unknown;
  const league = rounded(eventLeaguePriorFrom(rows));
  const teams = rounded(summariseTeamSeason(teamMatchesFrom(rows)));

  await writeFileAtomically(
    PRIOR_FILE,
    `// generated by npm run data:prior from the ${season} dataset; don't edit by hand.
// last season for the live prediction: league averages, each team's strength,
// and each player's totals in the order of SEASON_SUMMARY_FIELDS, keyed by
// fpl's stable code
import type { LastSeasonPrior } from './build-projections.js';

export const LAST_SEASON_PRIOR: LastSeasonPrior = {
  season: '${season}',
  league: ${JSON.stringify(league, null, 2)},
  teams: ${JSON.stringify(teams, null, 2)},
  players: {
${players.join('\n')}
  },
};
`,
  );
  console.log(
    `written: lib/projection-prior.ts (${season}, ${players.length} players)`,
  );
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
