const STORED_DECIMALS = 4;

/** lib/analysis/event-weights.ts: the fitted numbers as a typed constant */
export function formatEventWeightsModule(
  weights: EventWeights,
  fit: { seasons: readonly string[]; vaastavCommit: string },
): string {
  return `// generated by npm run eval:events; don't edit by hand. fitted on the tune
// seasons together, after leave-one-season-out cross-validation chose the
// finishing strength. see results/events.md for what each number means
import type { EventWeights } from './event-projection.js';

export const EVENT_WEIGHTS: EventWeights = ${JSON.stringify(roundDeep(weights), null, 2)};

export const EVENT_FIT = ${JSON.stringify(
    { seasons: fit.seasons, vaastavCommit: fit.vaastavCommit },
    null,
    2,
  )} as const;
`;
}

function roundDeep(value: unknown): unknown {
  if (typeof value === 'number') return Number(value.toFixed(STORED_DECIMALS));
  if (typeof value !== 'object' || value === null) return value;
  return Object.fromEntries(
    Object.entries(value).map(([key, inner]) => [key, roundDeep(inner)]),
  );
}

export interface HaulRow {
  label: string;
  summary: readonly {
    id: HaulMetricId;
    value: number | null;
    interval: Interval | null;
  }[];
}

export interface EventsReportInput {
  reports: readonly BaselineReport[];
  context: ReportContext;
  /** event model minus step 3, on the same resampled gameweeks */
  metricDifferences: readonly { id: MetricId; difference: Difference }[];
  haulRows: readonly HaulRow[];
  haulDifferences: readonly { id: HaulMetricId; difference: Difference }[];
  finalWeights: EventWeights;
  folds: readonly { trainedOn: string; scoredOn: string; weights: EventWeights }[];
  finishingLosses: readonly { strength: number; losses: readonly number[] }[];
  lossSeasons: readonly string[];
  calibration: Record<Position, Calibration>;
  typicalFullGame: FullGameFeatures;
  captains: readonly {
    label: string;
    top: readonly { name: string; gameweeks: number }[];
  }[];
  disagreement: CaptainDisagreement;
}

type Reading = 'event' | 'step3' | 'unclear';

/** which model the paired interval favours, or neither when it spans 0 */
function readingOf(difference: Difference, better: 'lower' | 'higher'): Reading {
  const interval = difference.interval;
  if (interval === null) return 'unclear';
  const eventAhead = better === 'lower' ? interval.high < 0 : interval.low > 0;
  const step3Ahead = better === 'lower' ? interval.low > 0 : interval.high < 0;
  if (eventAhead) return 'event';
  if (step3Ahead) return 'step3';
  return 'unclear';
}

const READING_TEXT: Record<Reading, string> = {
  event: 'Event model ahead',
  step3: 'Step 3 ahead',
  unclear: 'No clear difference',
};

function signedCell(difference: Difference, unit = ''): string {
  const sign = (value: number) =>
    `${value >= 0 ? '+' : '-'}${Math.abs(value).toFixed(unit === '' ? 2 : 1)}${unit}`;
  if (difference.value === null) return 'n/a';
  const interval = difference.interval;
  return interval === null
    ? sign(difference.value)
    : `${sign(difference.value)} [${sign(interval.low)}, ${sign(interval.high)}]`;
}

function metricLabel(id: MetricId): string {
  return METRICS.find((metric) => metric.id === id)?.label ?? id;
}

function metricBetter(id: MetricId): 'lower' | 'higher' {
  return METRICS.find((metric) => metric.id === id)?.better ?? 'lower';
}

function differenceTable(input: EventsReportInput): string {
  const [events, step3] = input.reports;
  return table(
    ['Metric', 'Event model', 'Step 3 model', 'Event minus step 3, paired', 'Reading'],
    input.metricDifferences.map(({ id, difference }) => [
      `${metricLabel(id)} ${arrow(metricBetter(id))}`,
      formatNumber(find(events?.pooled ?? [], id)?.value ?? null),
      formatNumber(find(step3?.pooled ?? [], id)?.value ?? null),
      signedCell(difference),
      READING_TEXT[readingOf(difference, metricBetter(id))],
    ]),
  );
}

function haulTable(input: EventsReportInput): string {
  return table(
    ['Model', ...HAUL_METRICS.map((metric) => `${metric.label} ↑`)],
    input.haulRows.map((row) => [
      row.label,
      ...HAUL_METRICS.map(({ id }) => {
        const found = row.summary.find((entry) => entry.id === id);
        const percentLike = id !== 'captainPoints';
        const show = (value: number) =>
          percentLike ? `${Math.round(value * 100)}%` : value.toFixed(2);
        if (found === undefined || found.value === null) return 'n/a';
        const interval = found.interval;
        return interval === null
          ? show(found.value)
          : `${show(found.value)} [${show(interval.low)}, ${show(interval.high)}]`;
      }),
    ]),
  );
}

function haulDifferenceTable(input: EventsReportInput): string {
  return table(
    ['Haul measure', 'Event minus step 3, paired', 'Reading'],
    input.haulDifferences.map(({ id, difference }) => [
      HAUL_METRICS.find((metric) => metric.id === id)?.label ?? id,
      id === 'captainPoints'
        ? signedCell(difference)
        : signedCell(scaleDifference(difference, 100), ' pp'),
      READING_TEXT[readingOf(difference, 'higher')],
    ]),
  );
}

function scaleDifference(difference: Difference, by: number): Difference {
  return {
    value: difference.value === null ? null : difference.value * by,
    interval:
      difference.interval === null
        ? null
        : { low: difference.interval.low * by, high: difference.interval.high * by },
  };
}

/** the decision, written from the paired intervals so it holds whatever they say */
function verdict(input: EventsReportInput): string {
  const reading = (id: MetricId) => {
    const found = input.metricDifferences.find((entry) => entry.id === id);
    return found === undefined
      ? 'unclear'
      : readingOf(found.difference, metricBetter(id));
  };
  const focus: MetricId[] = ['captainRegret', 'topFive'];
  const readings = focus.map(reading);
  const wins = readings.filter((value) => value === 'event').length;
  const losses = readings.filter((value) => value === 'step3').length;
  const clearElsewhere = input.metricDifferences
    .filter(({ id }) => !focus.includes(id))
    .map(({ id, difference }) => ({
      id,
      reading: readingOf(difference, metricBetter(id)),
    }))
    .filter(({ reading: value }) => value !== 'unclear')
    .map(
      ({ id, reading: value }) =>
        `${metricLabel(id)} (${value === 'event' ? 'event model' : 'step 3'} ahead)`,
    );
  const beats = wins > 0 && losses === 0;
  const elsewhere =
    clearElsewhere.length === 0
      ? 'On the other metrics no paired difference is clear either.'
      : `Elsewhere the clear paired differences are: ${clearElsewhere.join(', ')}. They are small next to the gap to FPL's xP.`;
  return beats
    ? `**The event model beats step 3 on what it was built for** (${focus
        .filter((_, index) => readings[index] === 'event')
        .map(metricLabel)
        .join(' and ')}), without being clearly worse on the other. ${elsewhere}`
    : `**The event model does not beat step 3.** On captain regret and top-${TOP_PICKS}, the paired intervals for the difference ${losses > 0 ? 'favour step 3 on at least one' : 'both include 0'}: modelling each event did not pick a better captain or a better top ${TOP_PICKS}. ${elsewhere} **Step 3 stays the production model.**`;
}

function captainParagraph(input: EventsReportInput): string {
  const lists = input.captains
    .map(
      ({ label, top }) =>
        `${label}: ${top.map(({ name, gameweeks }) => `${name} ${gameweeks}`).join(', ')}`,
    )
    .join('. ');
  const { gameweeks, disagreements, aPoints, bPoints } = input.disagreement;
  const where =
    aPoints === null || bPoints === null
      ? ''
      : ` In those, the event model's captain averaged ${aPoints.toFixed(2)} points and step 3's ${bPoints.toFixed(2)}${aPoints < bPoints ? ': sticking with the premium pick was usually right' : ': moving the armband paid off'}.`;
  return `**Who they captain** (gameweeks as captain). ${lists}. The two picked a different captain in ${disagreements} of ${gameweeks} gameweeks.${where} Step 3 leans on price and season points per appearance, which favours the premium players; the event model follows fixtures and recent xG, so it moves the armband more.`;
}

function percent(probability: number): string {
  return `${Math.round(probability * 100)}%`;
}

const POSITION_NAME: Record<Position, string> = {
  GK: 'keeper',
  DEF: 'defender',
  MID: 'midfielder',
  FWD: 'forward',
};

const FULL_GAME_LABEL: Record<FullGameFeature, string> = {
  intercept: 'start (a keeper)',
  recentStartShare: `share of the last ${RECENT_MATCHES} started`,
  recentAppearanceShare: `share of the last ${RECENT_MATCHES} with minutes`,
  seasonAppearanceShare: 'share of the season with minutes',
  priceMillions: 'price, per £1m',
  defender: 'defender',
  midfielder: 'midfielder',
  forward: 'forward',
};

const BONUS_LABEL: Record<BonusFeature, string> = {
  appearance: 'Any appearance',
  fullGame: '60+ minutes',
  goals: 'Per goal',
  assists: 'Per assist',
  defensiveCleanSheet: 'Clean sheet, keeper or defender',
  saves: 'Per save, keeper',
  defensiveGoalsConceded: 'Per goal conceded, keeper or defender',
};

function fullGameSentence(weights: EventWeights, typical: FullGameFeatures): string {
  const nailed = {
    ...typical,
    recentStartShare: 1,
    recentAppearanceShare: 1,
    seasonAppearanceShare: 1,
  };
  const byPosition = (['GK', 'DEF', 'MID', 'FWD'] as const).map((position) => {
    const features: FullGameFeatures = {
      ...nailed,
      defender: position === 'DEF' ? 1 : 0,
      midfielder: position === 'MID' ? 1 : 0,
      forward: position === 'FWD' ? 1 : 0,
    };
    return `${POSITION_NAME[position]} ${percent(logistic(dot(weights.fullGame, features)))}`;
  });
  const benched = logistic(
    dot(weights.fullGame, {
      ...typical,
      recentStartShare: 0,
      recentAppearanceShare: 1,
      midfielder: 1,
      defender: 0,
      forward: 0,
    }),
  );
  return `- **60 minutes or more.** Once on the pitch, a regular who started the last ${RECENT_MATCHES} reaches 60 minutes about this often: ${byPosition.join(', ')}. A midfielder who came off the bench in each of the last ${RECENT_MATCHES}, about ${percent(benched)}. A 60+ appearance averages ${weights.minutes.full.toFixed(0)} minutes, a shorter one ${weights.minutes.short.toFixed(0)}.`;
}

function plainWords(input: EventsReportInput): string {
  const weights = input.finalWeights;
  const { scales, bonus } = weights;
  const strongestBonus = [...BONUS_FEATURES]
    .filter((key) => key !== 'appearance')
    .sort((a, b) => Math.abs(bonus[b]) - Math.abs(bonus[a]))
    .slice(0, 3)
    .map(
      (key) =>
        `${BONUS_LABEL[key].toLowerCase()} ${bonus[key] >= 0 ? '+' : ''}${bonus[key].toFixed(2)}`,
    );
  return [
    `- **Chance of playing** is step 3's model, refitted in each fold on the same features. It is not repeated here; see [projection.md](projection.md).`,
    fullGameSentence(weights, input.typicalFullGame),
    `- **Finishing.** A player's goals per xG is blended with ${weights.finishingStrength} xG of "exactly on xG". So a player who has scored 15 from 10 xG is rated ${(((15 + weights.finishingStrength) / (10 + weights.finishingStrength)) * 100 - 100).toFixed(0)}% above their xG, not 50%: most over- or under-performance is luck.`,
    `- **FPL credits ${scales.assists.toFixed(2)} assists per xA.** FPL's assist rules are looser than an Opta assist (a rebound or a won penalty can count), so raw xA undercounts. Goals come out at ${scales.goals.toFixed(2)} per finishing-adjusted xG, saves at ${scales.saves.toFixed(2)} per expected save, goals conceded at ${scales.goalsConceded.toFixed(2)} per xG against.`,
    `- **Clean sheets are rarer than Poisson says.** Goals against are scaled by ${scales.cleanSheet.toFixed(2)} inside the clean sheet chance, so that it predicts as many clean sheets as were really kept. Real goals clump (one goal makes the next more likely), and own goals and some penalties sit outside xG.`,
    `- **Bonus**, the biggest weights: ${strongestBonus.join(', ')} bonus points each.`,
    `- **Other points** (cards, own goals, penalties, which the scoring events above leave out) average ${(['GK', 'DEF', 'MID', 'FWD'] as const).map((position) => `${POSITION_NAME[position]} ${weights.otherPoints[position].toFixed(2)}`).join(', ')} per appearance.`,
  ].join('\n');
}

function calibrationTable(calibration: Record<Position, Calibration>): string {
  const positions = ['GK', 'DEF', 'MID', 'FWD'] as const;
  return table(
    ['Event', ...positions.map((position) => `${position}: projected / actual`)],
    BREAKDOWN_KEYS.map((key) => [
      key === 'goalsConceded'
        ? 'goals conceded'
        : key === 'cleanSheet'
          ? 'clean sheet'
          : key,
      ...positions.map((position) => {
        const entry = calibration[position];
        return entry.projected[key] === 0 && entry.actual[key] === 0
          ? '·'
          : `${entry.projected[key].toFixed(2)} / ${entry.actual[key].toFixed(2)}`;
      }),
    ]),
  );
}

function foldTable(input: EventsReportInput): string {
  const rows: [string, (weights: EventWeights) => number][] = [
    ['Finishing strength (xG)', (weights) => weights.finishingStrength],
    ['Scale: goals', (weights) => weights.scales.goals],
    ['Scale: assists', (weights) => weights.scales.assists],
    ['Scale: saves', (weights) => weights.scales.saves],
    ['Scale: goals conceded', (weights) => weights.scales.goalsConceded],
    ['Scale: clean sheet', (weights) => weights.scales.cleanSheet],
    ['Minutes, 60+ appearance', (weights) => weights.minutes.full],
    ['Minutes, shorter appearance', (weights) => weights.minutes.short],
    ...FULL_GAME_FEATURES.map((key): [string, (weights: EventWeights) => number] => [
      `60+ log-odds: ${FULL_GAME_LABEL[key]}`,
      (weights) => weights.fullGame[key],
    ]),
    ...BONUS_FEATURES.map((key): [string, (weights: EventWeights) => number] => [
      `Bonus: ${BONUS_LABEL[key]}`,
      (weights) => weights.bonus[key],
    ]),
  ];
  return table(
    [
      'Number',
      ...input.folds.map((fold) => `Fit on ${fold.trainedOn}`),
      'Final (both)',
    ],
    rows.map(([label, read]) => [
      label,
      ...input.folds.map((fold) => read(fold.weights).toFixed(2)),
      read(input.finalWeights).toFixed(2),
    ]),
  );
}

function finishingTable(input: EventsReportInput): string {
  const best = (index: number) =>
    input.finishingLosses.reduce((a, b) =>
      (b.losses[index] ?? Infinity) < (a.losses[index] ?? Infinity) ? b : a,
    ).strength;
  return table(
    [
      'Finishing strength (xG)',
      ...input.lossSeasons.map((season) => `Goal log loss, ${season}`),
    ],
    input.finishingLosses.map(({ strength, losses }) => [
      String(strength),
      ...losses.map((loss, index) =>
        best(index) === strength ? `**${loss.toFixed(5)}**` : loss.toFixed(5),
      ),
    ]),
  );
}

export function formatEventsMarkdown(input: EventsReportInput): string {
  const { pooled, perSeason } = scoreTables(input.reports, 'Model');
  const [events, step3] = input.reports;
  const focusCells = (report: BaselineReport | undefined) =>
    `captain regret ${cell(find(report?.pooled ?? [], 'captainRegret'))}, top-${TOP_PICKS} ${cell(find(report?.pooled ?? [], 'topFive'))}`;

  return `# Event model

Generated by \`npm run eval:events\`. Don't edit by hand.

${scopeLine(input.reports, input.context)}

## Verdict

${verdict(input)}

- Event model: ${focusCells(events)}.
- Step 3 model: ${focusCells(step3)}.

Both models are scored out of fold: each tune season is predicted by weights fitted only on the other. The intervals for each model alone are wide, because a gameweek's captain and top ${TOP_PICKS} swing on a few hauls. The paired difference resamples the same gameweeks for both models, so the shared luck cancels; it is the fair way to compare them.

${differenceTable(input)}

## Did modelling events find hauls?

A haul is ${HAUL_POINTS}+ points. "${HAUL_POINTS}+ scores in the top ${CAPTAIN_POOL}" is the share of all hauls in a gameweek that the model had on its ${CAPTAIN_POOL}-player shortlist; a haul tied at the cut counts for its share of the open places, so the constant (everyone tied) scores what a random shortlist would.

${haulTable(input)}

Event model minus step 3, on the same resampled gameweeks (pp: percentage points):

${haulDifferenceTable(input)}

${captainParagraph(input)}

## All models

${pooled}

### Per season

${perSeason}

## How the model works

Projected points = chance of playing × the sum over the gameweek's fixtures of the expected points from each scoring event, given the player gets on. A double gameweek sums two fixtures, a blank has none and projects 0. It reads only the leak-proof history view, and FPL's scoring rules come from \`lib/analysis/fpl-scoring.ts\` (the 2022-23 to 2024-25 rules; 2025-26's defensive contribution points are not in them yet).

- **Chance of playing**: step 3's logistic model, unchanged.
- **Minutes**: a second logistic gives the chance of 60+ minutes once on, from the same playing-time features plus position. Expected minutes mix the average 60+ and shorter appearance.
- **Goals**: recent xG per 90 (last 6 appearances, blended with last season, then the league), times finishing (goals per xG over both seasons, shrunk toward 1), times how leaky the opponent's defence is and home or away.
- **Assists**: xA per 90 the same way, without finishing.
- **Team strength**: each team's xG for and against per match, blended with ${TEAM_PRIOR_MATCHES} matches of its own last season (promoted sides start from last season's bottom three). A fixture's expected goals are league average × attack × the opponent's defence × home or away.
- **Clean sheet**: only after 60+ minutes, chance of 0 goals against while on the pitch.
- **Goals conceded** (keepers and defenders): −1 per 2, worked out exactly on the Poisson distribution, not from the mean.
- **Saves** (keepers): the keeper's own saves per 90, scaled by the opponent's attack; 1 point per 3, again exact on the Poisson.
- **Bonus**: a linear model of bonus on the match's events, fitted on what actually happened, then fed the expected events. Capped at 0 to 3.
- **Appearance**: 2 points for 60+ minutes, 1 for less.
- **Other**: the average of what the events leave out (cards, own goals, penalties), per position.

**The Poisson assumption.** Goals, assists, goals conceded and saves are each treated as Poisson: independent events at a steady rate for the match, so the chance of none is e^(−mean). That is the standard first model for football counts. It is not quite right. Real goals clump a little, so Poisson overstates clean sheets (corrected by the clean sheet scale below) and slightly understates the chance of a brace or a hat-trick.

## What the fitted numbers say

The final numbers, fitted on both tune seasons together and saved in \`lib/analysis/event-weights.ts\`.

${plainWords(input)}

### Event by event: projected against actual

Average points per appearance from each event, for players who got on, out of fold (each season projected by the fold that didn't see it). A model built from the rules should match line by line, not only in total.

${calibrationTable(input.calibration)}

## Cross-validation

The finishing strength, scored by how well it predicts goals given the minutes played (Poisson log loss, lower is better; bold is each season's best). Each fold uses the strength that was best on its training season.

${finishingTable(input)}

Every fitted number from each fold next to the final fit:

${foldTable(input)}

## How it's measured

${MEASUREMENT_NOTES}

## Baselines

${describeProjectors(input.reports.slice(2))}
`;
}
