const TEST_SEASON = EVAL_SPLITS.test.join(', ');
const PENDING = '**Status: registered, not yet scored.**';
const SCORED =
  '**Status: scored once.** Everything below the rule was added by that single run; the rule and w above are as registered.';

export interface RegistrationInput {
  context: ReportContext;
  weight: number;
  tuneSeasons: readonly string[];
  tunePlayerGameweeks: number;
}

/**
 * the rule, written to the results file before the test season is loaded.
 * the hash ties the scoring run to exactly this text and this w
 */
export function registration(input: RegistrationInput): { text: string; hash: string } {
  const body = `# Final test: ${TEST_SEASON}

Generated by \`npm run eval:test:register\` and then, once, \`npm run eval:test\`. Don't edit by hand.

## Pre-registered rule

Written before ${TEST_SEASON} was loaded. Everything scored is fitted on ${input.tuneSeasons.join(' and ')} only; nothing is tuned on ${TEST_SEASON}. After this run the projection model is frozen: these results are not used to tune it.

**What is scored**

- **Two-part model (step 3)**: \`lib/analysis/projection-weights.ts\`, fitted on both tune seasons.
- **Event model (step 4)**: \`lib/analysis/event-weights.ts\`, fitted on both tune seasons.
- **Blend**: w x two-part + (1 - w) x event, with **w = ${input.weight.toFixed(4)}**: the least squares weight over every player with a fixture in both tune seasons (${input.tunePlayerGameweeks} player-gameweeks), using the two models above, kept to [0, 1].
- Both models add the defensive contribution rule for ${TEST_SEASON} (2 points at 10 for defenders, 12 for midfielders and forwards, never keepers), as a rule-based term on top, not fitted.

**Primary, deciding.** The blend against the two-part model, paired on the same resampled gameweeks (95% bootstrap interval), on top-${TOP_PICKS} hit, haul share in the top ${CAPTAIN_POOL} and captain regret. **The blend ships if it is not clearly worse on any of the three**: no interval for the difference lies entirely on the wrong side of 0. If it is clearly worse on any one, the two-part model stays.

**Secondary, reported, not deciding.** Both models (and the blend) against the baselines, form (30 days), points per game, last 3 gameweeks and constant 2, with FPL's xP shown but flagged as leaky, on all the usual metrics.

**Known before scoring.** ${EVAL_SPLITS.tune.at(-1) ?? ''} did not record defensive contributions, so in ${TEST_SEASON} both models' defensive contribution rate starts from a prior of 0 and builds up from each player's own ${TEST_SEASON} appearances. That understates the term, most in the early gameweeks. It is the same in both models, so the primary comparison is unaffected. The baselines read real points totals, which include defensive contribution points, so the secondary comparison is slightly tilted toward them. In the live app last season always records the stat, so this does not arise there.`;
  const hash = createHash('sha256').update(body).digest('hex');
  return { text: `${body}\n\n<!-- registration ${hash} -->\n\n${PENDING}\n`, hash };
}

/** throws unless the file holds exactly this registration, not yet scored */
export function assertRegistered(file: string | null, hash: string): void {
  if (file === null) {
    throw new Error('no registration found. run npm run eval:test:register first');
  }
  if (!file.includes(`<!-- registration ${hash} -->`)) {
    throw new Error(
      'the registered rule or w differs from what this run would score; the rule cannot change after registering',
    );
  }
  if (!file.includes(PENDING)) {
    throw new Error(
      `${TEST_SEASON} has already been scored; it is scored exactly once`,
    );
  }
}

export interface ScoredModel {
  label: string;
  metrics: MetricSummary[];
  hauls: { id: HaulMetricId; value: number | null; interval: Interval | null }[];
}

export interface TestResultsInput {
  context: ReportContext;
  /** the season scored: the test season, or a tune season in a rehearsal */
  season: string;
  registered: string;
  blend: ScoredModel;
  twoPart: ScoredModel;
  blendDifferences: Record<DecisionMeasureId, Difference>;
  decision: Decision;
  eventDifferences: Record<DecisionMeasureId, Difference>;
  eventDecision: Decision;
  eventLabel: string;
  reports: readonly BaselineReport[];
  haulRows: readonly ScoredModel[];
  /** null for a season that didn't score defensive contributions */
  defensive: {
    all: CallSummary;
    byPosition: { position: string; summary: CallSummary }[];
  } | null;
}

export function formatTestMarkdown(input: TestResultsInput): string {
  const scope = input.reports[0];
  const gameweeks = scope?.run.gameweeks.length ?? 0;
  const playerGameweeks = scope?.run.projections.length ?? 0;
  const registered = input.registered.replace(PENDING, SCORED);
  return `${registered}
## Verdict

${verdict(input)}

${input.season}: ${gameweeks} gameweeks, ${playerGameweeks} player-gameweeks. Data: vaastav/Fantasy-Premier-League at \`${input.context.vaastavCommit.slice(0, 7)}\`. Intervals are 95% bootstrap intervals over whole gameweeks (${input.context.resamples} resamples, seed ${input.context.seed}). ↓ lower is better, ↑ higher is better.

## Primary: the blend against the two-part model

${table(
  [
    'Model',
    ...DECISION_MEASURES.map(({ label, better }) => `${label} ${arrow(better)}`),
  ],
  [input.blend, input.twoPart].map((model) => [
    model.label,
    ...DECISION_MEASURES.map(({ id }) => decisionCell(model, id)),
  ]),
)}

${table(
  ['Blend minus two-part, paired (pp: percentage points)', 'Difference'],
  DECISION_MEASURES.map(({ id, label }) => [
    label,
    readingCell(input.blendDifferences[id], input.decision.readings[id], id),
  ]),
)}

For reference, not deciding: the event model alone minus the two-part model.

${table(
  [`${input.eventLabel} minus two-part, paired`, 'Difference'],
  DECISION_MEASURES.map(({ id, label }) => [
    label,
    readingCell(input.eventDifferences[id], input.eventDecision.readings[id], id),
  ]),
)}

## Secondary: against the baselines

${table(
  ['Model', ...METRICS.map((metric) => `${metric.label} ${arrow(metric.better)}`)],
  input.reports.map((report) => [
    report.projector.label,
    ...METRICS.map((metric) => cell(find(report.pooled, metric.id))),
  ]),
)}

A haul is ${HAUL_POINTS}+ points.

${table(
  ['Model', ...HAUL_METRICS.map(({ label }) => `${label} ↑`)],
  input.haulRows.map((model) => [
    model.label,
    ...HAUL_METRICS.map(({ id }) => {
      const found = model.hauls.find((entry) => entry.id === id);
      return id === 'captainPoints' ? valueCell(found) : percentCell(found);
    }),
  ]),
)}

${defensiveSection(input.defensive)}

## How it's measured

${MEASUREMENT_NOTES}
- **Haul share in the top ${CAPTAIN_POOL}**: the share of each gameweek's ${HAUL_POINTS}+ point scores that the model had on its ${CAPTAIN_POOL}-player shortlist.

## Models and baselines

${describeProjectors(input.reports)}
`;
}

function verdict(input: TestResultsInput): string {
  const worse = DECISION_MEASURES.filter(
    ({ id }) => input.decision.readings[id] === 'worse',
  ).map(({ label }) => label.toLowerCase());
  const better = DECISION_MEASURES.filter(
    ({ id }) => input.decision.readings[id] === 'better',
  ).map(({ label }) => label.toLowerCase());
  const detail = `Clearly better on ${better.length === 0 ? 'none' : better.join(', ')}; clearly worse on ${worse.length === 0 ? 'none' : worse.join(', ')}.`;
  return input.decision.ship
    ? `**The blend passes: it is not clearly worse than the two-part model on any of the three measures.** ${detail} By the rule, the blend is the model to ship. Nothing is wired here.`
    : `**The blend fails: it is clearly worse than the two-part model on ${worse.join(', ')}.** ${detail} By the rule, the two-part model stays.`;
}

function decisionCell(model: ScoredModel, id: DecisionMeasureId): string {
  if (id === 'haulsShortlisted') {
    return percentCell(model.hauls.find((entry) => entry.id === id));
  }
  return cell(find(model.metrics, id));
}

function defensiveSection(defensive: TestResultsInput['defensive']): string {
  if (defensive === null) return '';
  return `## Defensive contributions in ${TEST_SEASON}

The rule-based term's chance of reaching the count, against how often it was reached, over appearances by players who can earn it. Reported to show the size of the known gap above, not to tune it.

${table(
  ['Position', 'Appearances', 'Chance given', 'Reached'],
  [
    ...defensive.byPosition.map(({ position, summary }) =>
      defensiveRow(position, summary),
    ),
    defensiveRow('All', defensive.all),
  ],
)}`;
}

function defensiveRow(label: string, summary: CallSummary): string[] {
  const percent = (value: number) => `${(value * 100).toFixed(1)}%`;
  return [
    label,
    String(summary.appearances),
    percent(summary.predicted),
    percent(summary.actual),
  ];
}
