import { join } from 'node:path';
import {
  DEFENSIVE_CONTRIBUTION_POINTS,
  DEFENSIVE_CONTRIBUTION_THRESHOLD,
  defensiveContributionPoints,
} from '../../lib/analysis/fpl-scoring.js';
import type { Position } from '../../lib/analysis/types.js';
import {
  callsByBand,
  constantBrier,
  defensiveContributionCalls,
  summariseCalls,
} from '../../lib/eval/defensive-contribution-check.js';
import type { DefensiveContributionCall } from '../../lib/eval/defensive-contribution-check.js';
import { buildGameweekCases } from '../../lib/eval/snapshot.js';
import { EVAL_SPLITS } from '../../lib/eval/splits.js';
import { writeFileAtomically } from '../data/http.js';
import { table } from './report.js';
import { RESULTS_DIR, failLoudly, readSeasons, readVaastavCommit } from './shared.js';

const LIVE_SEASON = EVAL_SPLITS.live[0];
// the season before: read as history for its priors, never scored
const HISTORY_SEASON = EVAL_SPLITS.test[0];
const SCORED_POSITIONS: readonly Position[] = ['DEF', 'MID', 'FWD'];

// npm run eval:defensive: the rule-based defensive contribution term against
// what happened in the live season's finished gameweeks
async function main(): Promise<void> {
  const vaastavCommit = await readVaastavCommit();
  const loaded = await readSeasons([HISTORY_SEASON, LIVE_SEASON]);
  const [history, live] = loaded;
  if (history === undefined || live === undefined) throw new Error('seasons missing');
  const calls = defensiveContributionCalls(
    buildGameweekCases(loaded, LIVE_SEASON),
    live.rows,
  );
  const gameweeks = [...new Set(calls.map((call) => call.gameweek))].sort(
    (a, b) => a - b,
  );

  // the bar to clear: last season's share reaching the count, by position
  const lastSeasonRate = new Map(
    SCORED_POSITIONS.map((position) => {
      const apps = history.rows.filter(
        (row) => row.position === position && row.minutes > 0,
      );
      const reached = apps.filter(
        (row) => defensiveContributionPoints(position, row.defensiveContribution) > 0,
      ).length;
      return [position, apps.length === 0 ? 0 : reached / apps.length] as const;
    }),
  );
  const rateOf = (call: DefensiveContributionCall) =>
    lastSeasonRate.get(call.position) ?? 0;

  const percent = (value: number) => `${(value * 100).toFixed(1)}%`;
  const points = (value: number) => (value * DEFENSIVE_CONTRIBUTION_POINTS).toFixed(3);
  const row = (label: string, group: readonly DefensiveContributionCall[]) => {
    const summary = summariseCalls(group);
    return [
      label,
      String(summary.appearances),
      percent(summary.predicted),
      percent(summary.actual),
      points(summary.predicted),
      points(summary.actual),
      summary.brier.toFixed(4),
      constantBrier(group, rateOf).toFixed(4),
    ];
  };
  const header = [
    'Group',
    'Appearances',
    'Chance given',
    'Reached',
    'Expected pts',
    'Actual pts',
    'Brier',
    'Brier, last season rate',
  ];
  const overall = summariseCalls(calls);
  const gap = overall.actual === 0 ? 0 : 1 - overall.predicted / overall.actual;
  const beatsConstant = overall.brier < constantBrier(calls, rateOf);

  const markdown = `# Defensive contributions

Generated by \`npm run eval:defensive\`. Don't edit by hand.

${LIVE_SEASON} gameweeks ${gameweeks[0] ?? '?'} to ${gameweeks.at(-1) ?? '?'}: every appearance by a defender, midfielder or forward (${calls.length} in all). ${HISTORY_SEASON} is read only as last season's history for the priors; nothing is fitted or scored on it. Data: vaastav/Fantasy-Premier-League at \`${vaastavCommit.slice(0, 7)}\` and FPL's API.

## The rule term

From 2025-26, FPL gives ${DEFENSIVE_CONTRIBUTION_POINTS} points for ${DEFENSIVE_CONTRIBUTION_THRESHOLD.DEF} defensive contributions by a defender, or ${DEFENSIVE_CONTRIBUTION_THRESHOLD.MID} by a midfielder or forward (recoveries count for them). The step 3 model was fitted on seasons without these points, so they are taken out of every past total it reads and added back on top as a rule:

- **Rate**: the player's defensive contributions per 90 over his last 6 appearances, blended with last season's per 90 (by FPL's stable player code) and then the league's for his position.
- **Chance**: Poisson at that rate, worked out for the minutes of each of his recent appearances and averaged, so a full game and a cameo keep their very different chances.
- **Points if he plays**: chance × ${DEFENSIVE_CONTRIBUTION_POINTS}, for each fixture. The projection multiplies it by the chance of playing like the rest of the points.

## How it did

**It ${gap >= 0 ? 'understates' : 'overstates'} them by about ${Math.abs(Math.round(gap * 100))}%**: an average chance of ${percent(overall.predicted)} given against ${percent(overall.actual)} reached. ${beatsConstant ? "It still tells players apart: its Brier score (lower is better) beats always guessing last season's rate for the position." : "Its Brier score (lower is better) doesn't beat always guessing last season's rate for the position, so it adds little beyond position."}

${table(header, [
  ...SCORED_POSITIONS.map((position) =>
    row(
      position,
      calls.filter((call) => call.position === position),
    ),
  ),
  row('**All**', calls),
])}

By how long the appearance turned out to be. The model doesn't know this before the deadline, which is why short appearances are overstated and full games understated:

${table(header, [
  row(
    '60+ minutes',
    calls.filter((call) => call.minutes >= 60),
  ),
  row(
    'Under 60',
    calls.filter((call) => call.minutes < 60),
  ),
])}

Calibration, by the chance given:

${table(
  ['Chance given', 'Appearances', 'Average chance', 'Reached'],
  callsByBand(calls).map(({ low, high, summary }) => [
    `${Math.round(low * 100)} to ${Math.min(100, Math.round(high * 100))}%`,
    String(summary.appearances),
    summary.appearances === 0 ? '·' : percent(summary.predicted),
    summary.appearances === 0 ? '·' : percent(summary.actual),
  ]),
)}

## Why it runs low

- **Uncertain rates.** Reaching 10 or 12 is in the tail of the distribution. A player's true rate is uncertain, and one best-guess rate is too sure in both directions: in the calibration table, low chances come true more often than given and the few high ones less often. Shrinking toward the league average steadies the rate but pulls the tail in further.
- **Clumping.** Some matches (a side pinned back all game) pile up defensive actions, while Poisson assumes a steady rate within a match.
- Fixing it would mean fitting a correction, and the only seasons with these points are the locked test season and the live one being checked here. So it is left as a known, stated underestimate: worth about ${points(overall.actual - overall.predicted)} points per appearance.
`;
  await writeFileAtomically(join(RESULTS_DIR, 'defensive-contributions.md'), markdown);
  console.log(
    `defensive contributions: chance ${percent(overall.predicted)} given, ${percent(overall.actual)} reached over ${calls.length} appearances`,
  );
  console.log('written: results/defensive-contributions.md');
}

main().catch(failLoudly);
