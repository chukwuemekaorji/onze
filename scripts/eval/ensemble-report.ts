import type { MetricSummary } from '../../lib/eval/backtest.js';
import type { Interval } from '../../lib/eval/bootstrap.js';
import { HAUL_POINTS } from '../../lib/eval/compare.js';
import type { Difference, HaulMetricId } from '../../lib/eval/compare.js';
import { DECISION_MEASURES, POSITIONS } from '../../lib/eval/ensemble.js';
import type { Decision, DecisionMeasureId, Reading } from '../../lib/eval/ensemble.js';
import { CAPTAIN_POOL, TOP_PICKS } from '../../lib/eval/metrics.js';
import type { Position } from '../../lib/analysis/types.js';
import {
  MEASUREMENT_NOTES,
  cell,
  find,
  formatNumber,
  scopeLine,
  scoreTables,
  table,
} from './report.js';
import type { BaselineReport, ReportContext } from './report.js';

export interface CandidateRow {
  id: 'twoPart' | 'event' | 'blend' | 'blendByPosition' | 'routing';
  label: string;
  /** an ensemble the decision rule is applied to; the rest are reference rows */
  candidate: boolean;
  metrics: MetricSummary[];
  hauls: { id: HaulMetricId; value: number | null; interval: Interval | null }[];
  /** this row minus the two-part model, paired */
  differences: Record<DecisionMeasureId, Difference>;
  decision: Decision;
}

export interface FoldWeights {
  trainedOn: string;
  scoredOn: string;
  weight: number;
  byPosition: Record<Position, number>;
}

export interface EnsembleReportInput {
  context: ReportContext;
  reports: readonly BaselineReport[];
  rows: readonly CandidateRow[];
  foldWeights: readonly FoldWeights[];
  byPositionDifferences: Record<DecisionMeasureId, Difference>;
  byPositionDecision: Decision;
  routingLabel: string;
  blendLabels: { single: string; byPosition: string };
}

/**
 * the rule is part of the generated file and sits above every number, so it
 * reads as what was decided before the run, not a summary written after it
 */
export const DECISION_RULE = `An ensemble ships only if, against the two-part model alone on the same resampled gameweeks (paired bootstrap, 95% interval), it is **clearly better on at least one** of top-${TOP_PICKS} hit, haul share in the top ${CAPTAIN_POOL} or captain regret (the interval for the difference excludes 0 in its favour) **and clearly worse on none** of them (no interval excluding 0 against it). Otherwise the two-part model stays and the negative result is recorded.

- A separate w per position replaces the single w only if it passes the same test against the single-w blend.
- Routing's captain is the two-part model's own pick, so its captain regret is the two-part model's exactly; its case rests on top-${TOP_PICKS} and haul share.
- If both ensembles pass, both are recorded as candidates and nothing is chosen here. Wiring one into the app is a separate step.

This rule was written into the script that generates this file before the first ensemble run, and the verdict below is computed from it, not written by hand.`;

const READING_TEXT: Record<Reading, string> = {
  better: 'Clearly better',
  worse: 'Clearly worse',
  unclear: 'No clear difference',
};

export function formatEnsembleMarkdown(input: EnsembleReportInput): string {
  const { pooled, perSeason } = scoreTables(input.reports, 'Model');
  return `# Ensembles of the two-part and event models

Generated by \`npm run eval:ensemble\`. Don't edit by hand.

${scopeLine(input.reports, input.context)}

## Decision rule

${DECISION_RULE}

## Decision

${verdict(input)}

## The decision measures

${measuresTable(input.rows)}

Against the two-part model, on the same resampled gameweeks (pp: percentage points):

${differencesTable(input.rows)}

The event model is a reference row: step 4 already found it doesn't beat the two-part model, and it is not a candidate here.

## One w or one per position

${byPositionSection(input)}

## The blend weights

w is the two-part model's share: 1 is the two-part model alone, 0 the event model alone. In each fold both models are fitted on the training season, and w is the least squares weight over every player with a fixture in that same season, kept to [0, 1]. The held season's results never touch the models or w.

${weightsTable(input.foldWeights)}

The weights are chosen on the season the models were fitted on, so both models look a little better there than they will out of sample. With two tune seasons there is no third to choose w on without reusing the held one. Each model has a few dozen fitted numbers against tens of thousands of player-gameweeks a season, so the bias should be small, and the scored season is out of fold either way.

## All metrics

The routing ensemble is not one projection, so it has no MAE or Spearman; its decision measures are above.

${pooled}

### Per season

${perSeason}

## How it's measured

${MEASUREMENT_NOTES}
- **Haul share in the top ${CAPTAIN_POOL}**: the share of each gameweek's ${HAUL_POINTS}+ point scores that the model had on its ${CAPTAIN_POOL}-player shortlist, as in [events.md](events.md).
- **Routing**: top-${TOP_PICKS} and haul share are read from the event model's ranking (the transfer shortlist), captain regret and captain points from the two-part model's (the armband).
`;
}

function verdict(input: EnsembleReportInput): string {
  const candidates = input.rows.filter((row) => row.candidate);
  const passing = candidates.filter((row) => row.decision.ship);
  const lines = candidates.map((row) => {
    const wins = measuresWith(row.decision, 'better');
    const losses = measuresWith(row.decision, 'worse');
    const detail = [
      wins.length > 0
        ? `clearly better on ${wins.join(', ')}`
        : 'clearly better on nothing',
      losses.length > 0
        ? `clearly worse on ${losses.join(', ')}`
        : 'clearly worse on nothing',
    ].join('; ');
    return `- **${row.label}**: ${row.decision.ship ? 'passes' : 'does not pass'} (${detail}).`;
  });
  const headline =
    passing.length === 0
      ? '**No ensemble passes. The two-part model stays the production model.**'
      : passing.length === 1
        ? `**${passing[0]?.label ?? ''} passes the rule.** It is the candidate to wire in; nothing is wired yet.`
        : `**${passing.map((row) => row.label).join(' and ')} both pass the rule.** Both are recorded as candidates; nothing is chosen or wired here.`;
  return `${headline}\n\n${lines.join('\n')}`;
}

function measuresWith(decision: Decision, reading: Reading): string[] {
  return DECISION_MEASURES.filter(({ id }) => decision.readings[id] === reading).map(
    ({ label }) => label.toLowerCase(),
  );
}

function measuresTable(rows: readonly CandidateRow[]): string {
  const haul = (row: CandidateRow, id: HaulMetricId) =>
    row.hauls.find((entry) => entry.id === id);
  return table(
    [
      'Model',
      `Top-${TOP_PICKS} hit ↑`,
      `Haul share in the top ${CAPTAIN_POOL} ↑`,
      'Captain regret ↓',
      'Captain, average points ↑',
    ],
    rows.map((row) => [
      row.label,
      cell(find(row.metrics, 'topFive')),
      percentCell(haul(row, 'haulsShortlisted')),
      cell(find(row.metrics, 'captainRegret')),
      valueCell(haul(row, 'captainPoints')),
    ]),
  );
}

function differencesTable(rows: readonly CandidateRow[]): string {
  return table(
    ['Model minus two-part', ...DECISION_MEASURES.map(({ label }) => label), 'Passes'],
    rows
      .filter((row) => row.id !== 'twoPart')
      .map((row) => [
        row.label,
        ...DECISION_MEASURES.map(({ id }) =>
          readingCell(row.differences[id], row.decision.readings[id], id),
        ),
        row.candidate ? (row.decision.ship ? 'Yes' : 'No') : 'Reference',
      ]),
  );
}

function byPositionSection(input: EnsembleReportInput): string {
  const { single, byPosition } = input.blendLabels;
  const rows = DECISION_MEASURES.map(({ id, label }) => [
    label,
    readingCell(
      input.byPositionDifferences[id],
      input.byPositionDecision.readings[id],
      id,
    ),
  ]);
  const kept = input.byPositionDecision.ship
    ? `**The per-position weights are kept**: they clearly beat the single w on at least one measure and are clearly worse on none, so "${byPosition}" is the blend candidate.`
    : `**The per-position weights are not kept**: they don't clearly beat the single w, so "${single}" is the blend candidate and "${byPosition}" is shown for reference only.`;
  return `${kept}\n\n${table([`${byPosition} minus ${single}`, 'Paired difference'], rows)}`;
}

function weightsTable(folds: readonly FoldWeights[]): string {
  return table(
    [
      'Trained on',
      'Scored on',
      'One w',
      ...POSITIONS.map((position) => `w, ${position}`),
    ],
    folds.map((fold) => [
      fold.trainedOn,
      fold.scoredOn,
      formatNumber(fold.weight),
      ...POSITIONS.map((position) => formatNumber(fold.byPosition[position])),
    ]),
  );
}

export function readingCell(
  difference: Difference,
  reading: Reading,
  id: DecisionMeasureId,
): string {
  const text =
    id === 'haulsShortlisted'
      ? signed(scaled(difference, 100), ' pp')
      : signed(difference, '');
  return `${text}: ${READING_TEXT[reading].toLowerCase()}`;
}

function scaled(difference: Difference, factor: number): Difference {
  return {
    value: difference.value === null ? null : difference.value * factor,
    interval:
      difference.interval === null
        ? null
        : {
            low: difference.interval.low * factor,
            high: difference.interval.high * factor,
          },
  };
}

export function signed(difference: Difference, unit: string): string {
  const decimals = unit === '' ? 2 : 1;
  const sign = (value: number) =>
    `${value >= 0 ? '+' : '-'}${Math.abs(value).toFixed(decimals)}${unit}`;
  if (difference.value === null) return 'n/a';
  const interval = difference.interval;
  return interval === null
    ? sign(difference.value)
    : `${sign(difference.value)} [${sign(interval.low)}, ${sign(interval.high)}]`;
}

export function percentCell(
  summary: { value: number | null; interval: Interval | null } | undefined,
): string {
  if (summary === undefined || summary.value === null) return 'n/a';
  const percent = (value: number) => `${Math.round(value * 100)}%`;
  const interval = summary.interval;
  return interval === null
    ? percent(summary.value)
    : `${percent(summary.value)} [${percent(interval.low)}, ${percent(interval.high)}]`;
}

export function valueCell(
  summary: { value: number | null; interval: Interval | null } | undefined,
): string {
  if (summary === undefined || summary.value === null) return 'n/a';
  const interval = summary.interval;
  return interval === null
    ? formatNumber(summary.value)
    : `${formatNumber(summary.value)} [${formatNumber(interval.low)}, ${formatNumber(interval.high)}]`;
}
