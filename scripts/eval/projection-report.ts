const STORED_DECIMALS = 4;

/** lib/analysis/projection-weights.ts: the fitted numbers as a typed constant */
export function formatWeightsModule(
  weights: ProjectionWeights,
  fit: { seasons: readonly string[]; pointsPenalty: number; vaastavCommit: string },
): string {
  const round = <K extends string>(record: Record<K, number>) =>
    Object.fromEntries(
      Object.entries<number>(record).map(([key, value]) => [
        key,
        Number(value.toFixed(STORED_DECIMALS)),
      ]),
    );
  return `// generated by npm run eval:projection; don't edit by hand. fitted on the
// tune seasons together, after leave-one-season-out cross-validation chose
// the penalty. see results/projection.md for what each weight means
import type { ProjectionWeights } from './projection.js';

export const PROJECTION_WEIGHTS: ProjectionWeights = ${JSON.stringify(
    {
      chanceOfPlaying: round(weights.chanceOfPlaying),
      pointsIfPlaying: round(weights.pointsIfPlaying),
    },
    null,
    2,
  )};

export const PROJECTION_FIT = ${JSON.stringify(
    {
      seasons: fit.seasons,
      pointsPenalty: fit.pointsPenalty,
      vaastavCommit: fit.vaastavCommit,
    },
    null,
    2,
  )} as const;
`;
}

const PLAY_LABEL: Record<PlayFeature, string> = {
  intercept: 'Starting log-odds',
  recentStartShare: `Share of the last ${RECENT_MATCHES} club matches started`,
  recentAppearanceShare: `Share of the last ${RECENT_MATCHES} club matches with any minutes`,
  seasonAppearanceShare: "Share of this season's club matches with any minutes",
  priceMillions: 'Price, per £1m',
};

const POINTS_LABEL: Record<PointsFeature, string> = {
  goalkeeper: 'Base, goalkeeper',
  defender: 'Base, defender',
  midfielder: 'Base, midfielder',
  forward: 'Base, forward',
  seasonPointsPerAppearance: 'Points per appearance, this season',
  formPointsPerAppearance: `Points per appearance, last ${FORM_WINDOW_DAYS} days`,
  lastThreePointsPerAppearance: `Points per appearance, last ${RECENT_MATCHES} gameweeks`,
  attackingPointsPerAppearance: 'xG and xA per appearance, as FPL points',
  priceMillions: 'Price, per £1m',
  defensiveFixtureDifficulty: 'Fixture difficulty above 3, keeper or defender',
  attackingFixtureDifficulty: 'Fixture difficulty above 3, midfielder or forward',
  home: 'Playing at home',
};

const POSITION_FEATURES = ['goalkeeper', 'defender', 'midfielder', 'forward'] as const;
const POSITION_NAMES: Record<(typeof POSITION_FEATURES)[number], string> = {
  goalkeeper: 'keeper',
  defender: 'defender',
  midfielder: 'midfielder',
  forward: 'forward',
};

function percent(probability: number): string {
  return `${Math.round(probability * 100)}%`;
}

function signed(value: number): string {
  return `${value >= 0 ? '+' : '-'}${Math.abs(value).toFixed(2)}`;
}

function mean<K extends string>(examples: readonly Example<K>[], key: K): number {
  return (
    examples.reduce((sum, example) => sum + example.features[key], 0) / examples.length
  );
}

function spread<K extends string>(examples: readonly Example<K>[], key: K): number {
  const average = mean(examples, key);
  const variance =
    examples.reduce((sum, example) => sum + (example.features[key] - average) ** 2, 0) /
    examples.length;
  return Math.sqrt(variance);
}

function typicalPlay(set: TrainingSet): PlayFeatures {
  return Object.fromEntries(
    PLAY_FEATURES.map((key) => [key, mean(set.play, key)]),
  ) as PlayFeatures;
}

function playTable(weights: ProjectionWeights, set: TrainingSet): string {
  const typical = typicalPlay(set);
  const chance = (features: PlayFeatures) =>
    logistic(dot(weights.chanceOfPlaying, features));
  return table(
    ['Feature', 'Weight', 'What it means'],
    PLAY_FEATURES.map((key) => {
      const weight = weights.chanceOfPlaying[key];
      let meaning = 'Where the odds start with every feature at 0';
      if (key === 'priceMillions') {
        meaning = `£1m more moves a typical player from ${percent(chance(typical))} to ${percent(
          chance({ ...typical, priceMillions: typical.priceMillions + 1 }),
        )}`;
      } else if (key !== 'intercept') {
        meaning = `From none to all, a typical player goes from ${percent(
          chance({ ...typical, [key]: 0 }),
        )} to ${percent(chance({ ...typical, [key]: 1 }))}`;
      }
      return [PLAY_LABEL[key], signed(weight), meaning];
    }),
  );
}

function pointsTable(weights: ProjectionWeights, set: TrainingSet): string {
  return table(
    ['Feature', 'Weight', 'Typical swing', 'What it means'],
    POINTS_FEATURES.map((key) => {
      const weight = weights.pointsIfPlaying[key];
      const isBase = (POSITION_FEATURES as readonly string[]).includes(key);
      const swing = isBase ? '' : signed(weight * spread(set.points, key));
      let meaning = `Each extra point here ${weight >= 0 ? 'adds' : 'takes away'} ${Math.abs(
        weight,
      ).toFixed(2)}`;
      if (isBase) meaning = 'Where this position starts, before the terms below';
      if (key === 'priceMillions')
        meaning = `Each £1m ${weight >= 0 ? 'adds' : 'takes away'} ${Math.abs(weight).toFixed(2)}`;
      if (
        key === 'defensiveFixtureDifficulty' ||
        key === 'attackingFixtureDifficulty'
      ) {
        meaning = `Each step harder ${weight <= 0 ? 'costs' : 'adds'} ${Math.abs(weight).toFixed(2)}`;
      }
      if (key === 'home') meaning = `${signed(weight)} at home`;
      return [POINTS_LABEL[key], signed(weight), swing, meaning];
    }),
  );
}

/** a few sentences that hold whatever the fitted numbers turn out to be */
function plainWords(weights: ProjectionWeights, set: TrainingSet): string {
  const swings = POINTS_FEATURES.filter(
    (key) => !(POSITION_FEATURES as readonly string[]).includes(key),
  )
    .map((key) => ({
      key,
      swing: Math.abs(weights.pointsIfPlaying[key] * spread(set.points, key)),
    }))
    .sort((a, b) => b.swing - a.swing);
  const [first, second] = swings;
  const typicalByPosition = POSITION_FEATURES.map((position) => {
    const group = set.points.filter((example) => example.features[position] === 1);
    const typical = Object.fromEntries(
      POINTS_FEATURES.map((key) => [key, mean(group, key)]),
    ) as PointsFeatures;
    return `${POSITION_NAMES[position]} ${dot(weights.pointsIfPlaying, typical).toFixed(2)}`;
  });
  const typical = typicalPlay(set);
  const chance = (features: Partial<PlayFeatures>) =>
    percent(logistic(dot(weights.chanceOfPlaying, { ...typical, ...features })));
  const defensive = weights.pointsIfPlaying.defensiveFixtureDifficulty;
  const attacking = weights.pointsIfPlaying.attackingFixtureDifficulty;

  return [
    `- **Who plays comes first.** A regular who started the last ${RECENT_MATCHES} and played every match so far is given about ${chance({ recentStartShare: 1, recentAppearanceShare: 1, seasonAppearanceShare: 1 })} to play; one benched for the last ${RECENT_MATCHES} who has played half the season, about ${chance({ recentStartShare: 0, recentAppearanceShare: 0, seasonAppearanceShare: 0.5 })}.`,
    `- **Once on the pitch, a typical player scores** about: ${typicalByPosition.join(', ')} points.`,
    first !== undefined && second !== undefined
      ? `- **The biggest scoring signals** are "${POINTS_LABEL[first.key]}" and "${POINTS_LABEL[second.key]}": a typical difference between two players in each moves the projection by ${first.swing.toFixed(2)} and ${second.swing.toFixed(2)} points.`
      : '',
    `- **Fixtures**: each step of difficulty ${defensive <= 0 ? 'costs' : 'adds'} a keeper or defender ${Math.abs(defensive).toFixed(2)} and ${attacking <= 0 ? 'costs' : 'adds'} a midfielder or forward ${Math.abs(attacking).toFixed(2)}; home is worth ${signed(weights.pointsIfPlaying.home)}.`,
    '- Form, the last 3 gameweeks and the season average all measure points per appearance, so they share credit between them. Read them together, not one by one.',
  ]
    .filter((line) => line !== '')
    .join('\n');
}

function foldTable(
  folds: readonly FoldWeights[],
  finalWeights: ProjectionWeights,
): string {
  const header = [
    'Weight',
    ...folds.map((fold) => `Fit on ${fold.trainedOn}`),
    'Final (both)',
  ];
  const rows = [
    ...PLAY_FEATURES.map((key) => [
      `Play: ${PLAY_LABEL[key]}`,
      ...folds.map((fold) => signed(fold.weights.chanceOfPlaying[key])),
      signed(finalWeights.chanceOfPlaying[key]),
    ]),
    ...POINTS_FEATURES.map((key) => [
      `Points: ${POINTS_LABEL[key]}`,
      ...folds.map((fold) => signed(fold.weights.pointsIfPlaying[key])),
      signed(finalWeights.pointsIfPlaying[key]),
    ]),
  ];
  return table(header, rows);
}

export interface ProjectionReportInput {
  reports: readonly BaselineReport[];
  context: ReportContext;
  folds: readonly FoldWeights[];
  finalWeights: ProjectionWeights;
  training: TrainingSet;
  penaltyErrors: readonly { penalty: number; error: number }[];
  chosenPenalty: number;
  linkage: readonly { season: string; played: number; linked: number }[];
}

export function formatProjectionMarkdown(input: ProjectionReportInput): string {
  const { reports, context, folds, finalWeights, training } = input;
  const { pooled, perSeason } = scoreTables(reports, 'Model');
  const penalties = table(
    ['Penalty', 'Cross-validated RMSE, points if playing'],
    input.penaltyErrors.map(({ penalty, error }) => [
      penalty === input.chosenPenalty ? `**${penalty}** (chosen)` : String(penalty),
      formatNumber(error),
    ]),
  );
  const linkage = input.linkage
    .map(
      ({ season, played, linked }) =>
        `${season}: ${linked} of ${played} player-gameweeks with minutes (${percent(linked / played)})`,
    )
    .join('; ');

  return `# Projection model

Generated by \`npm run eval:projection\`. Don't edit by hand.

${scopeLine(reports, context)}

${pooled}

The model's row is out of fold: 2023-24 is scored with weights fitted on 2024-25 alone, and 2024-25 with weights fitted on 2023-24. The baselines are the same as in [baselines.md](baselines.md). Every row's interval resamples the same gameweeks, so rows can be compared directly.

## Per season

${perSeason}

## How the model works

Projected points = chance of playing × expected points if playing, summed over the gameweek's fixtures (a double gameweek has two, a blank has none and projects 0). It reads only the leak-proof history view.

- **Chance of playing** is a logistic regression on the share of the last ${RECENT_MATCHES} club matches started, the share with any minutes, the share of this season's matches with minutes, and price.
- **Points if playing** is a linear blend of a base per position; points per appearance this season, over the last ${FORM_WINDOW_DAYS} days and over the last ${RECENT_MATCHES} gameweeks; expected goals and assists per 90 over the last ${RECENT_APPEARANCES_FOR_XGI} appearances, turned into FPL points over the player's usual minutes; price; fixture difficulty (separately for defensive and attacking players); and home or away.
- **Last season as a prior.** Every rate is blended with ${PRIOR_APPEARANCES} appearances (or 90s) of prior evidence: the player's own numbers from last season, found by FPL's stable player code, or the league average for their position if they are new. So in gameweek 1 a proven scorer starts from last season, not from a flat 2. Matched by code: ${linkage}.
- The fit uses one example per player per fixture: all of them for chance of playing, those with minutes for points if playing. Points if playing uses a ridge penalty chosen by cross-validation; chance of playing a light fixed one.

## What the weights say

The final weights, fitted on both tune seasons together. These are the numbers saved in \`lib/analysis/projection-weights.ts\`.

${plainWords(finalWeights, training)}

### Chance of playing

${playTable(finalWeights, training)}

### Points if playing

"Typical swing" is the weight times the feature's usual spread between players: how much a normal difference in that feature moves the projection.

${pointsTable(finalWeights, training)}

## Cross-validation

The penalty on points if playing, chosen by leave-one-season-out error:

${penalties}

The weights from each fold next to the final fit. If a weight changes sign between folds, don't read much into it.

${foldTable(folds, finalWeights)}

## How it's measured

${MEASUREMENT_NOTES}

## Baselines

${describeProjectors(reports.slice(1))}
`;
}
