const PENDING = '**Status: registered, not yet run.**';
const DONE =
  '**Status: run once.** Everything below the rule was added by that single run; the rule above is as registered.';

export interface RegistrationInput {
  squads: number;
  seasons: readonly { season: string; weights: string }[];
  resamples: number;
  seed: number;
}

/** the rule, written before any season is played. the hash ties the run to it */
export function registration(input: RegistrationInput): { text: string; hash: string } {
  const seasons = input.seasons
    .map((entry) => `- **${entry.season}**: ${entry.weights}`)
    .join('\n');
  const body = `# Decision backtest

Generated by \`npm run backtest:register\` and then, once, \`npm run backtest\`. Don't edit by hand.

## Pre-registered rule

Written before any season was played. Nothing in the app or the models is tuned on these results; the app is not changed by this run.

**What is played.** Whole seasons, deadline by deadline, with FPL's real results: a 15-man squad, £100.0m, three per club, free transfers rolling over (at most 5, one going into gameweek 2), -4 hits, auto-subs, the captain's points doubled and the vice-captain's if the captain doesn't play, real price changes, and FPL's selling price (half of any rise, rounded down). No chips. Each deadline, a policy sees only data from before that gameweek.

**Seasons and model weights.**

${seasons}

**Start squads.** ${input.squads} per season, the same for every policy, built at gameweek 1 from last season's data only: squad 1 is the best guess (the most FPL points last season that fits the budget, the squad shape and three per club, picked greedily while the rest can still be afforded at the cheapest prices); squads 2 to ${input.squads} multiply each player's points last season by e^(${START_SQUAD_NOISE} z), z a seeded normal draw, and pick the same way. Players new to the league count 0.

**Policies.** Every policy picks its eleven, bench order, captain and vice-captain with the app's own lineup and captaincy code, on its own numbers.

1. **No transfers**: the start squad all season; eleven and captain by the model.
2. **Form greedy**: the app's one-week transfer logic, but every number is FPL's form (points per match over the last 30 days, times the week's fixtures). Eleven and captain by form too.
3. **Onze one-week**: the app's one-week transfer logic on the model's numbers, as the app runs it now.
4. **Onze planner**: the app's ${PLAN_WEEKS}-week planner as it is now (K = ${PLAN_BEAM_WIDTH}, each week weighted ${WEEK_DECAY} of the one before, the same hit rules), replanned every deadline, playing only that week's part.

**Headline, deciding.** Onze planner minus Onze one-week in season points (after hits), paired on the same start squads and gameweeks, averaged over the start squads and then over the three seasons. The 95% interval resamples whole gameweeks within each season (${input.resamples} resamples, seed ${input.seed}), so it carries the luck of the weeks that every squad shares. **If the planner is not clearly worse (the interval's top is not below 0), it becomes the app's single source of this week's advice.** Otherwise the one-week logic stays.

**Also reported, not deciding.** Each Onze policy against no transfers and against form greedy, the same way; season totals for every policy; each season on its own; and two example seasons in plain words.

**Known before running.**

- The archive has no team news, so the model sees injuries only through missing minutes, as every policy does. A player who has left the league is shown as unavailable from the gameweek after his last row.
- The fixture list is read as it was finally played, so postponed matches show up in their final gameweek.
- There are no mini-leagues, so the no-hits-when-leading rule never applies.
- Three seasons is few. The interval carries week-to-week luck within those seasons, not how different another season might be.`;
  const hash = createHash('sha256').update(body).digest('hex');
  return { text: `${body}\n\n<!-- registration ${hash} -->\n\n${PENDING}\n`, hash };
}

export function assertRegistered(file: string | null, hash: string): void {
  if (file === null)
    throw new Error('no registration found. run npm run backtest:register first');
  if (!file.includes(`<!-- registration ${hash} -->`)) {
    throw new Error(
      'the registered rule differs from what this run would play; it cannot change after registering',
    );
  }
  if (!file.includes(PENDING))
    throw new Error('the backtest has already been run; it runs once');
}

export interface ResultsInput {
  registered: string;
  labels: Record<PolicyId, string>;
  runs: Record<PolicyId, SeasonRun[]>;
  headline: PairedDifference;
  comparisons: { a: PolicyId; b: PolicyId; difference: PairedDifference }[];
  examples: { season: string; squadNumber: number }[];
  minutes: number;
}

const ORDER: readonly PolicyId[] = [
  'onze-planner',
  'onze-one-week',
  'form-greedy',
  'no-transfers',
];

export function formatResults(input: ResultsInput): string {
  const seasons = [
    ...new Set(input.runs['onze-planner'].map((run) => run.season)),
  ].sort();
  return `${input.registered.replace(PENDING, DONE)}
## Verdict

${verdict(input)}

## Season totals

Average season points per start squad (after hits), with the worst and best start squad in brackets, and the transfers and hits per season.

${table(
  ['Policy', ...seasons, 'Transfers a season', 'Hits a season'],
  ORDER.map((id) => {
    const runs = input.runs[id];
    return [
      input.labels[id],
      ...seasons.map((season) =>
        totalCell(runs.filter((run) => run.season === season)),
      ),
      average(runs.map((run) => run.transfers)).toFixed(1),
      average(runs.map((run) => run.hits)).toFixed(1),
    ];
  }),
)}

## Paired differences

Season points per start squad, first policy minus second, on the same squads and gameweeks. 95% intervals over resampled gameweeks.

${table(
  ['Comparison', 'All seasons', ...seasons, 'Reading'],
  [
    {
      a: 'onze-planner' as const,
      b: 'onze-one-week' as const,
      difference: input.headline,
    },
    ...input.comparisons,
  ].map(({ a, b, difference }) => [
    `${input.labels[a]} minus ${input.labels[b]}`,
    differenceCell(difference.value, difference.interval),
    ...seasons.map((season) => {
      const entry = difference.bySeason.find((row) => row.season === season);
      return entry === undefined ? 'n/a' : differenceCell(entry.value, entry.interval);
    }),
    READING_TEXT[readDifference(difference)],
  ]),
)}

## Two seasons in plain words

${input.examples.map((example) => exampleSentence(input, example)).join('\n\n')}

## Run

All ${seasons.length} seasons, ${ORDER.length} policies and every start squad took ${input.minutes.toFixed(1)} minutes.
`;
}

function verdict(input: ResultsInput): string {
  const { value, interval } = input.headline;
  const reading = readDifference(input.headline);
  const sizes = `Onze planner minus Onze one-week: ${signed(value)} points a season [${signed(interval.low)}, ${signed(interval.high)}].`;
  if (plannerShips(input.headline)) {
    const how =
      reading === 'better'
        ? 'It is clearly better.'
        : 'It is not clearly better either: the interval includes 0.';
    return `**The planner is not clearly worse, so by the rule it becomes the app's single source of this week's advice.** ${sizes} ${how} Nothing in the app is changed by this run.`;
  }
  return `**The planner is clearly worse, so by the rule the one-week logic stays.** ${sizes}`;
}

const READING_TEXT: Record<'better' | 'worse' | 'unclear', string> = {
  better: 'First clearly ahead',
  worse: 'Second clearly ahead',
  unclear: 'No clear difference',
};

function exampleSentence(
  input: ResultsInput,
  example: { season: string; squadNumber: number },
): string {
  const total = (id: PolicyId) =>
    input.runs[id].find(
      (run) => run.season === example.season && run.squadNumber === example.squadNumber,
    )?.total ?? 0;
  const planner = total('onze-planner');
  const oneWeek = total('onze-one-week');
  const none = total('no-transfers');
  const formTotal = total('form-greedy');
  const squad =
    example.squadNumber === 1
      ? 'the best-guess squad (#1)'
      : `squad #${example.squadNumber}`;
  return `**${example.season}, ${squad}.** Following Onze's planner from ${squad}, you would have finished ${example.season} with ${Math.round(planner)} points, against ${Math.round(oneWeek)} following its one-week advice, ${Math.round(none)} making no transfers at all and ${Math.round(formTotal)} chasing form. That's ${aboutDifference(planner - oneWeek)} than the one-week advice and ${aboutDifference(planner - formTotal)} than chasing form.`;
}

function aboutDifference(points: number): string {
  const whole = Math.round(Math.abs(points));
  if (whole === 0) return 'about the same';
  return `${whole} point${whole === 1 ? '' : 's'} ${points > 0 ? 'more' : 'fewer'}`;
}

function totalCell(runs: readonly SeasonRun[]): string {
  if (runs.length === 0) return 'n/a';
  const totals = runs.map((run) => run.total);
  return `${Math.round(average(totals))} [${Math.round(Math.min(...totals))}, ${Math.round(Math.max(...totals))}]`;
}

function differenceCell(value: number, interval: Interval): string {
  return `${signed(value)} [${signed(interval.low)}, ${signed(interval.high)}]`;
}

function signed(value: number): string {
  return `${value >= 0 ? '+' : '-'}${Math.abs(value).toFixed(1)}`;
}

function average(values: readonly number[]): number {
  return values.length === 0
    ? 0
    : values.reduce((sum, value) => sum + value, 0) / values.length;
}
