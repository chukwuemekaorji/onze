import type { AnalysisSummary } from '../lib/analysis-summary.js';

/**
 * the bundled example: a fictional manager run through the real analysis on
 * real fpl data, so people without a team can explore. lives in
 * web/fixtures/sample-summary.json and loads as its own chunk, only when needed
 */

// the example's deadline always sits this far ahead, so its countdown is live
export const SAMPLE_DEADLINE_LEAD_MS = (2 * 24 + 4) * 60 * 60 * 1000;

/** shifts the sample's deadlines and timestamp so they read as current */
export function withFreshDates(summary: AnalysisSummary, now: number): AnalysisSummary {
  const originalDeadline = new Date(summary.currentEventDeadline).getTime();
  const shift = Number.isFinite(originalDeadline)
    ? now + SAMPLE_DEADLINE_LEAD_MS - originalDeadline
    : 0;
  // an unreadable date is passed through as is; toISOString would throw on it
  const shifted = (iso: string) => {
    const time = new Date(iso).getTime();
    return Number.isFinite(time) ? new Date(time + shift).toISOString() : iso;
  };

  return {
    ...summary,
    generatedAt: new Date(now).toISOString(),
    currentEventDeadline: shifted(summary.currentEventDeadline),
    nextEvent: summary.nextEvent
      ? { ...summary.nextEvent, deadline: shifted(summary.nextEvent.deadline) }
      : null,
  };
}

export async function loadSampleSummary(
  now: number = Date.now(),
): Promise<AnalysisSummary> {
  const module = await import('./fixtures/sample-summary.json');
  // json imports widen literal unions like position to string; the fixture is
  // generated by the real pipeline and checked in test/sample-summary.test.ts
  return withFreshDates(module.default as unknown as AnalysisSummary, now);
}
